"""Foreground lifetime owner for the explicit test-classpath performance server."""
from perf_common import *
entries=(Q/'drone-rental/target/perf-classpath.txt').read_text().strip().split(os.pathsep)
assert all(Path(p).is_file() for p in entries),'Use a local classpath generated by Maven in this checkout'
classpath=os.pathsep.join([str(Q/'drone-rental/target/test-classes'),str(Q/'drone-rental/target/classes'),*entries])
java=str(Path(os.environ['JAVA_HOME'])/'bin'/('java.exe' if os.name=='nt' else 'java'))
env=os.environ.copy();env['LEASEGUARD_JOBS_ENABLED']='true' if '--worker' in sys.argv else 'false'
with (L/'backend.log').open('ab') as log:
 process=subprocess.Popen([java,'-Xms128m','-Xmx384m','-cp',classpath,'com.drone.rental.PerfG5Launcher'],cwd=Q,env=env,stdout=log,stderr=subprocess.STDOUT,**({'creationflags':subprocess.CREATE_NO_WINDOW} if os.name=='nt' else {}))
 (L/'backend.json').write_text(json.dumps({'pid':process.pid}));print('Perf Java PID:',process.pid,'; Ctrl+C stops this owned process')
 try:process.wait()
 except KeyboardInterrupt:
  if process.poll() is None:process.terminate();process.wait(timeout=30)
